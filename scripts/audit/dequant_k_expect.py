    ('Q5_K', 3, 33, ''), ('Q5_K', 4, 34, ''), ('Q5_K', 5, 35, ''),
    ('Q5_K', 32, 36, 'first HIGH-nibble half: mask u2 and the second (scale,min) pair'),
