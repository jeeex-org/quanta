#!/usr/bin/env python3
"""tests/f32_enc_gen.py -- assemble tests/lfm2_f32_kernels.s and print the exact
byte sequence of every labelled instruction, in the form the Quanta
jit_x86_fused.quanta builders want:  label = hexstring (nbytes)

The bytes are produced by GNU `as` and read back out of `objdump -d`, i.e. NOT
derived by hand. This is the SAME discipline the existing fused kernels use.

Usage: python3 tests/f32_enc_gen.py [path/to/lfm2_f32_kernels.s]
"""
import re
import subprocess
import sys
import os
import tempfile

SRC = sys.argv[1] if len(sys.argv) > 1 else "tests/lfm2_f32_kernels.s"

# The Q4_K f32 factor prologue, in the order the kernel executes it. `as` decides
# the bytes (and their lengths); this list decides only the order.
PROLOGUE = [
    "p_movd", "p_ph2ps", "p_perm_d", "p_perm_m",
    "p_ld_a", "p_ld_b", "p_ld_c",
    "p_shl_a", "p_shr_a", "p_cvt12", "p_mul12",
    "p_shl_b", "p_shr_b", "p_cvt14", "p_mul14",
    "p_shr_a6", "p_shl_a4", "p_shl_c28", "p_shr_c28", "p_or1", "p_cvt13", "p_mul13",
    "p_shr_b6", "p_shl_b4", "p_shr_c4", "p_or2", "p_cvt15", "p_mul15",
    "p_dup12", "p_dup13", "p_dup14", "p_dup15",
]


def main():
    d = tempfile.mkdtemp(prefix="f32enc")
    o = os.path.join(d, "k.o")
    r = subprocess.run(["as", "-o", o, SRC], capture_output=True, text=True)
    if r.returncode != 0:
        print("ASSEMBLE FAILED:\n" + r.stderr)
        return 1
    dis = subprocess.run(["objdump", "-d", "--insn-width=16", o],
                         capture_output=True, text=True).stdout
    cur = None
    out = {}
    order = []
    # objdump lines look like:
    #  0000000000000000 <r_zero>:
    #     0:  c5 fc 57 c0           vxorps %ymm0,%ymm0,%ymm0
    lab = re.compile(r'^[0-9a-f]+ <([^>]+)>:')
    ins = re.compile(r'^\s*[0-9a-f]+:\s*((?:[0-9a-f]{2} )+)\s*\t')
    for line in dis.splitlines():
        m = lab.match(line)
        if m:
            cur = m.group(1)
            continue
        m = ins.match(line)
        if m and cur:
            bs = m.group(1).split()
            if cur not in out:
                out[cur] = []
                order.append(cur)
            out[cur].extend(bs)
    if not out:
        print("no instructions parsed -- objdump format changed?")
        return 1
    for k in order:
        h = "".join(out[k])
        print("%-12s %2d  %s" % (k, len(out[k]), h))
    # also emit a C-friendly table for the execution verifier
    cf = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "lfm2_f32_enc_bytes.h")
    with open(cf, "w") as fh:
        fh.write("/* GENERATED by tests/lfm2_f32_enc_gen.py from tests/lfm2_f32_kernels.s.\n"
                 " * Do not hand-edit. Byte sequences come from GNU as + objdump. */\n")
        fh.write("typedef struct { const char *name; int len; unsigned char b[512]; } enc_t;\n")
        fh.write("static enc_t ENC[] = {\n")
        for k in order:
            bs = out[k]
            row = ", ".join("0x" + x for x in bs)
            fh.write('  { "%s", %d, { %s } },\n' % (k, len(bs), row))
        fh.write("};\n")
        fh.write("static const int ENC_N = %d;\n" % len(order))
    print("---")
    print("wrote %s (%d sequences)" % (cf, len(order)))

    # ---- splice the Q4_K factor prologue into the kernel --------------------
    # The kernel's prologue is GENERATED, not transcribed: the first attempt
    # hand-adapted it from the f64 kernel and four instructions sourced the wrong
    # register. `as` decides the bytes; this decides only the ORDER.
    src = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "lfm2_f32_kernels.s")
    mnem = {}
    for line in open(src):
        m = re.match(r'^(p_[a-z0-9_]+):\s+([^/\n]*?)\s*(?://.*)?$', line)
        if m:
            mnem[m.group(1)] = m.group(2).strip()
    qf = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "lib", "std", "jit_x86_fused.quanta")
    qf = os.path.normpath(qf)
    body = []
    for k in PROLOGUE:
        bs = out.get(k)
        if not bs:
            print("SPLICE FAIL: no bytes for %s" % k)
            return 1
        body.append('    femit("%s", %d)   // %s'
                    % ("".join(bs), len(bs), mnem.get(k, k)))
    txt = open(qf).read()
    a = txt.index("    // <<<F32 PROLOGUE GENERATED")
    b = txt.index("    // >>>END", a)
    head = txt[:a]
    tail = txt[b + len("    // >>>END"):]
    open(qf, "w").write(head + "    // <<<F32 PROLOGUE GENERATED"
                        " -- do not hand-edit; run\n"
                        "    //     `python3 tests/lfm2_f32_enc_gen.py` after"
                        " editing tests/lfm2_f32_kernels.s.\n"
                        + "\n".join(body) + "\n" + "    // >>>END" + tail)
    print("spliced %d instructions into %s" % (len(body), qf))
    return 0


if __name__ == "__main__":
    sys.exit(main())
