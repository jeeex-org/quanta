#!/usr/bin/env python3
"""Generate the large-prompt tokenizer reference for the special-path gate row.

WHY A SECOND FIXTURE
--------------------
tests/fixtures/tokenizer_ref.txt (gen_tokenizer_ref.py) covers 26 SHORT prompts
through the plain path. The A20 stall was size-dependent -- 10,890 bytes took
355 s because bpe_special_match() re-walked the packed vocab from index 0 for
EACH of the 124 specials at EVERY pre-token boundary -- so a short-prompt fixture
can never catch it: at "Hello" (1 pre-token) the walk is free. This fixture is
ONE >=10 KB prompt whose ~2,300 pre-token boundaries exercise exactly that loop,
and it is the input the defect was measured on.

The oracle is upstream's OWN binary, `test-tokenizer-0`, as it was for
tokenizer_ref.txt: upstream's compiled code path, not a transcription of BPE.

PROMPT NOTE: the prompt (tests/lfm2_prefill_prompt.txt) contains NO control
tokens (`<|...|>`), so bpe_encode_special() and bpe_encode() must produce the
SAME ids on it -- the special path is exercised by its per-boundary MATCH LOOP,
which is where the stall was. Both are checked against this fixture in
stdlib_lfm2_bpe_special_scale_test.quanta.

Writes:
    tests/fixtures/lfm2_bpe_special_scale_ref.txt

    format:
        # <header lines>
        # count <n>
        <one decimal token id per line>

Run deliberately, by hand, when the fixture or the prompt changes:
    python3 tests/gen_bpe_special_scale_ref.py
"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

TEST_BIN = '/opt/ai/llama.cpp/build/bin/test-tokenizer-0'
DEFAULT_MODEL = '/opt/ai/models/quanta/QUANTA-LFM2.5-2.6Bv1-Q4_K_M.gguf'
DEFAULT_PROMPT = 'tests/lfm2_prefill_prompt.txt'
DEFAULT_OUT = 'tests/fixtures/lfm2_bpe_special_scale_ref.txt'
MIN_BYTES = 10240


def main():
    model = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_MODEL
    prompt_path = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_PROMPT
    out_path = sys.argv[3] if len(sys.argv) > 3 else DEFAULT_OUT

    if not os.path.exists(TEST_BIN):
        print('missing upstream test binary: %s' % TEST_BIN, file=sys.stderr)
        print('build it: cmake --build build --target test-tokenizer-0',
              file=sys.stderr)
        return 1

    with open(prompt_path, 'rb') as fh:
        raw = fh.read()
    if len(raw) < MIN_BYTES:
        print('prompt %s is %d bytes; the row needs >= %d'
              % (prompt_path, len(raw), MIN_BYTES), file=sys.stderr)
        return 1
    md5 = hashlib.md5(raw).hexdigest()

    workdir = tempfile.mkdtemp(prefix='bpescale_')
    try:
        inp = os.path.join(workdir, 'input.txt')
        with open(inp, 'wb') as fh:
            fh.write(raw)
        proc = subprocess.run([TEST_BIN, model, inp],
                              capture_output=True, cwd=workdir, timeout=600)
        stdout = proc.stdout.decode('utf-8', 'replace')
        if 'Tests passed' not in stdout:
            print('tokenizer run failed:\n%s'
                  % proc.stderr.decode('utf-8', 'replace')[-2000:],
                  file=sys.stderr)
            return 1
        tok = inp + '.tokcpp'
        if not os.path.exists(tok):
            print('no token output written', file=sys.stderr)
            return 1
        with open(tok) as fh:
            ids = [int(x) for x in fh.read().split() if x.strip()]
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    if not ids:
        print('empty id list', file=sys.stderr)
        return 1

    with open(out_path, 'w') as fh:
        fh.write('# GENERATED by tests/gen_bpe_special_scale_ref.py '
                 '-- DO NOT EDIT\n')
        fh.write('# upstream llama.cpp %s\n' % TEST_BIN)
        fh.write('# model %s\n' % os.path.basename(model))
        fh.write('# prompt %s bytes %d md5 %s\n' % (prompt_path, len(raw), md5))
        fh.write('# special=true (control/user_defined matched literally, as '
                 'bpe_encode_special does)\n')
        fh.write('# count %d\n' % len(ids))
        for t in ids:
            fh.write('%d\n' % t)

    print('prompt : %s (%d bytes, md5 %s)' % (prompt_path, len(raw), md5))
    print('binary : %s' % TEST_BIN)
    print('wrote  : %s -- %d ids (first=%d last=%d)'
          % (out_path, len(ids), ids[0], ids[-1]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
